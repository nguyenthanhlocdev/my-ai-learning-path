# Kiểu dữ liệu và Biến
# Kiểu dữ liệu cơ bản
# Kiểu số nguyên (Integer)
a = 10
print("Kiểu dữ liệu của a:", type(a))
# Kiểu số thực (Float)
b = 3.14
print("Kiểu dữ liệu của b:", type(b))
# Kiểu chuỗi (String)
c = "Hello, World!"
print("Kiểu dữ liệu của c:", type(c))
# Kiểu boolean (Boolean)
d = True
print("Kiểu dữ liệu của d:", type(d))
# Biến
x = 5
y = 2.5
z = "Python"
print("Giá trị của x:", x)
print("Giá trị của y:", y)
print("Giá trị của z:", z)
# Thay đổi giá trị của biến
x = 10
y = 4.5
z = "Programming"
print("Giá trị mới của x:", x)
print("Giá trị mới của y:", y)
print("Giá trị mới của z:", z)

# Kiểu dữ liệu phức tạp
# Kiểu danh sách (List)
my_list = [1, 2, 3, 4, 5]
print("Kiểu dữ liệu của my_list:", type(my_list))
# Kiểu tuple (Tuple)
my_tuple = (1, 2, 3, 4, 5)
print("Kiểu dữ liệu của my_tuple:", type(my_tuple))
# Kiểu từ điển (Dictionary)
my_dict = {"name": "Alice", "age": 30, "city": "New York"}
print("Kiểu dữ liệu của my_dict:", type(my_dict))
# Kiểu tập hợp (Set)
my_set = {1, 2, 3, 4, 5}
print("Kiểu dữ liệu của my_set:", type(my_set))


# Kiểu dữ liệu None
none_value = None
print("Kiểu dữ liệu của none_value:", type(none_value))


# Kiểu dữ liệu phức tạp có thể chứa các kiểu dữ liệu khác nhau
complex_data = [1, "Hello", 3.14, True, None, [1, 2, 3], {"key": "value"}]
print("Kiểu dữ liệu của complex_data:", type(complex_data))

# Kiểu dữ liệu có thể được sử dụng để lưu trữ và xử lý thông tin trong chương trình. Việc hiểu rõ về các kiểu dữ liệu sẽ giúp bạn viết mã hiệu quả và tránh lỗi khi làm việc với dữ liệu.